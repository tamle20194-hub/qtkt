import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const FIELDS = [
  'indication',
  'contraindication',
  'performer',
  'equipment',
  'duration',
];

function readArg(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? '' : process.argv[index + 1];
}

function readRows(file) {
  if (!file) throw new Error('Thiếu đường dẫn dữ liệu đầu vào');
  const rows = JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));
  if (!Array.isArray(rows)) throw new Error(`${file}: dữ liệu không phải mảng`);
  return rows;
}

function baseTitle(value) {
  return String(value ?? '')
    .normalize('NFKC')
    .toLocaleLowerCase('vi')
    .replace(/[‐‑‒–—―]/gu, '-')
    .replace(/\s+/gu, ' ')
    .trim();
}

function punctuationTitle(value) {
  return baseTitle(value)
    .replace(/[\p{P}\p{S}]+/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim();
}

function asciiTitle(value) {
  return punctuationTitle(value)
    .normalize('NFD')
    .replace(/\p{M}+/gu, '')
    .replaceAll('đ', 'd');
}

function prefixTitle(value) {
  return asciiTitle(value)
    .replace(/^(?:huong dan )?(?:quy trinh ky thuat|quy trinh|ky thuat)\s+/u, '')
    .trim();
}

const MATCHERS = [
  ['case-whitespace-dash', baseTitle],
  ['punctuation', punctuationTitle],
  ['vietnamese-diacritics', asciiTitle],
  ['generic-prefix', prefixTitle],
];

function uniqueDocumentIndex(documents, normalize) {
  const grouped = new Map();
  for (const document of documents) {
    const key = normalize(document.name);
    if (!key) continue;
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push(document);
  }
  return new Map(
    [...grouped]
      .filter(([, rows]) => rows.length === 1)
      .map(([key, rows]) => [key, rows[0]]),
  );
}

function isPlaceholder(value) {
  return ['', '0', '#N/A'].includes(String(value ?? '').trim());
}

function isPlaceholderSource(value) {
  const normalized = String(value ?? '').trim().toLocaleLowerCase('vi');
  return (
    ['', '#n/a', 'n/a', 'bhyt'].includes(normalized)
    || normalized.includes('qtkt')
  );
}

function sqlLiteral(value) {
  return `'${String(value ?? '').replaceAll("'", "''")}'`;
}

function assignment(field) {
  return `${field} = case
    when coalesce(btrim(target.${field}), '') in ('', '0', '#N/A')
      and coalesce(btrim(incoming.${field}), '') not in ('', '0', '#N/A')
    then incoming.${field}
    else target.${field}
  end`;
}

function buildMappings(technical, documents) {
  const documentCodes = new Set(documents.map((row) => row.code));
  if (documentCodes.size !== documents.length) {
    throw new Error('Mã tài liệu bị trùng giữa kho BYT và BV115');
  }

  const indexes = MATCHERS.map(([method, normalize]) => ({
    method,
    normalize,
    documents: uniqueDocumentIndex(documents, normalize),
  }));
  const mappings = [];

  for (const row of technical) {
    if (documentCodes.has(row.source_code) || !isPlaceholderSource(row.source_code)) {
      continue;
    }

    for (const matcher of indexes) {
      const document = matcher.documents.get(matcher.normalize(row.name));
      if (!document) continue;

      const fieldsToFill = FIELDS.filter(
        (field) => isPlaceholder(row[field]) && !isPlaceholder(document[field]),
      );
      mappings.push({
        technicalCode: row.code,
        documentCode: document.code,
        method: matcher.method,
        expectedSourceCode: row.source_code,
        approved: row.approved === true,
        fieldsToFill,
      });
      break;
    }
  }

  if (new Set(mappings.map((row) => row.technicalCode)).size !== mappings.length) {
    throw new Error('Một kỹ thuật được ánh xạ nhiều lần');
  }

  return mappings;
}

function renderMigration(mappings) {
  if (mappings.length === 0) {
    throw new Error('Không tìm thấy ánh xạ an toàn để tạo migration');
  }

  const values = mappings.map((row) => `    (
      ${sqlLiteral(row.technicalCode)},
      ${sqlLiteral(row.documentCode)},
      ${sqlLiteral(row.method)},
      ${sqlLiteral(row.expectedSourceCode)}
    )`).join(',\n');
  const fillablePredicate = FIELDS.map((field) => `(
      coalesce(btrim(target.${field}), '') in ('', '0', '#N/A')
      and coalesce(btrim(incoming.${field}), '') not in ('', '0', '#N/A')
    )`).join('\n    or ');

  const migration = `-- Generated by scripts/build-title-link-migration.mjs.
-- Titles must resolve to exactly one document in the combined BYT/BV115
-- repository. Existing links and non-placeholder clinical content are kept.
-- The strongest match also treats Unicode dash variants as equivalent.

with mappings (
  technical_code,
  document_code,
  match_method,
  expected_source_code
) as (
  values
${values}
), documents as materialized (
  select code, name, indication, contraindication, performer, equipment, duration
  from public.byt_documents

  union all

  select code, name, indication, contraindication, performer, equipment, duration
  from public.bv115_documents
), incoming as materialized (
  select
    mappings.technical_code,
    mappings.expected_source_code,
    mappings.match_method,
    documents.code as document_code,
    documents.name as document_name,
    documents.indication,
    documents.contraindication,
    documents.performer,
    documents.equipment,
    documents.duration
  from mappings
  join documents on documents.code = mappings.document_code
)
update public.technical_procedures as target
set
  source_code = incoming.document_code,
  source_name = incoming.document_name,
  has_process = true,
  ${FIELDS.map(assignment).join(',\n  ')},
  updated_at = now()
from incoming
where target.code = incoming.technical_code
  and coalesce(target.source_code, '') = incoming.expected_source_code
  and (
    target.source_code is distinct from incoming.document_code
    or target.source_name is distinct from incoming.document_name
    or target.has_process is not true
    or ${fillablePredicate}
  );
`;

  return migration;
}

function buildReport(mappings, output) {
  const byMethod = Object.fromEntries(MATCHERS.map(([method]) => [method, {
    rows: mappings.filter((row) => row.method === method).length,
    approvedRows: mappings.filter((row) => row.method === method && row.approved).length,
  }]));
  const byField = Object.fromEntries(FIELDS.map((field) => [field, {
    rows: mappings.filter((row) => row.fieldsToFill.includes(field)).length,
    approvedRows: mappings.filter(
      (row) => row.approved && row.fieldsToFill.includes(field),
    ).length,
  }]));

  return {
    output: path.resolve(output),
    rows: mappings.length,
    approvedRows: mappings.filter((row) => row.approved).length,
    fillableRows: mappings.filter((row) => row.fieldsToFill.length > 0).length,
    fillableFields: mappings.reduce((sum, row) => sum + row.fieldsToFill.length, 0),
    byMethod,
    byField,
  };
}

function runCli() {
  const technical = readRows(readArg('technical'));
  const bytDocuments = readRows(readArg('byt'));
  const bv115Documents = readRows(readArg('bv115'));
  const output = readArg('output');
  if (!output) throw new Error('Cần truyền --output');

  const mappings = buildMappings(technical, [...bytDocuments, ...bv115Documents]);
  const migration = renderMigration(mappings);

  fs.writeFileSync(path.resolve(output), migration);

  console.log(JSON.stringify(buildReport(mappings, output), null, 2));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  runCli();
}

export {
  asciiTitle,
  baseTitle,
  buildMappings,
  prefixTitle,
  punctuationTitle,
  renderMigration,
};
